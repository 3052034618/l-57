import type { Task, ActivityData, Attachment, TaskVersion, AuditComment } from '../types';

const makeActivityData = (
  id: string,
  stage: ActivityData['stage'],
  name: string,
  quantity: number | null,
  unit: string,
  factorId: string | null,
  emission: number | null,
  description?: string,
): ActivityData => ({
  id,
  stage,
  name,
  description,
  quantity,
  unit,
  factorId,
  emission,
  remark: '',
});

const makeAttachment = (
  id: string,
  name: string,
  type: string,
  size: number,
  uploadTime: string,
): Attachment => ({
  id,
  name,
  type,
  size,
  uploadTime,
  url: `https://example.com/attachments/${id}`,
});

const makeVersion = (
  version: number,
  submitTime: string,
  submitter: string,
  data: ActivityData[],
  attachments: Attachment[],
  comment?: string,
): TaskVersion => ({
  version,
  submitTime,
  submitter,
  comment,
  data,
  attachments,
});

const makeComment = (
  id: string,
  taskId: string,
  version: number,
  author: string,
  authorRole: AuditComment['authorRole'],
  content: string,
  createdAt: string,
  references?: string[],
): AuditComment => ({
  id,
  taskId,
  version,
  author,
  authorRole,
  content,
  createdAt,
  references,
});

